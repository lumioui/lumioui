const path = (d, a = {}) => ({ e: "path", a: { d, ...a } });
const circle = (cx, cy, r, a = {}) => ({ e: "circle", a: { cx, cy, r, ...a } });
const line = (x1, y1, x2, y2, a = {}) => ({ e: "line", a: { x1, y1, x2, y2, ...a } });
const rect = (x, y, w, h, rx, a = {}) => ({ e: "rect", a: { x, y, width: w, height: h, rx, ...a } });
const ellipse = (cx, cy, rx, ry, a = {}) => ({ e: "ellipse", a: { cx, cy, rx, ry, ...a } });
const fill = (color = "currentColor") => ({ fill: color, stroke: "none" });
const A = (part, anims) => ({ ...part, anims });
const G = (id, children, a = {}) => ({ e: "g", g: id, a, children });
const an = (attr, values, times) => ({ kind: "attr", attr, values, times });
const tn = (type, values, times, extra = {}) => ({ kind: "transform", type, values, times, ...extra });

const f = (n) => Math.round(n * 10) / 10;

/* ---- bespoke gesture idioms -------------------------------------------
   HOLD phrasing: rest ~30%, act mid-cycle, settle back. Seamless loops.
   T2 staggers a second element's gesture a beat later. */
const HOLD = [0, 0.3, 0.55, 0.8, 1];
const T2 = [0, 0.42, 0.67, 0.92, 1];
/* scale-pop around a mark's own center (sAnims entry). */
const POP = (cx, cy, s = 1.24) => ({
  pivot: [cx, cy],
  anim: tn("scale", ["1", "1", `${s}`, "1", "1"], HOLD),
});
/* wiggle — rotate −a then +a around a pivot, with rest holds. */
const WIG = (cx, cy, a = 9) =>
  tn("rotate", [`0 ${cx} ${cy}`, `0 ${cx} ${cy}`, `-${a} ${cx} ${cy}`, `${a - 2} ${cx} ${cy}`, `0 ${cx} ${cy}`], HOLD);
/* dip — translate out along an axis and spring back (for gAnims). */
const DIP = (dx, dy) => tn("translate", ["0 0", "0 0", `${dx} ${dy}`, "0 0", "0 0"], HOLD);
/* blink — opacity dips once on a mark. */
const BLINK = (lo = 0.2) => [an("opacity", ["1", "1", `${lo}`, "1", "1"], [0, 0.32, 0.46, 0.6, 1])];
/* nudge one part along an axis, then spring back. */
const SHIFT = (p, dx, dy, t = HOLD) =>
  A(p, [tn("translate", ["0 0", "0 0", `${dx} ${dy}`, "0 0", "0 0"], t)]);
/* a vertical divider drags sideways, then releases (resize gesture). */
const DRAGV = (x1, y1, x2, y2, dx, t = HOLD) =>
  A(line(x1, y1, x2, y2), [
    an("x1", [`${x1}`, `${x1}`, `${x1 + dx}`, `${x1}`, `${x1}`], t),
    an("x2", [`${x2}`, `${x2}`, `${x2 + dx}`, `${x2}`, `${x2}`], t),
  ]);
/* a horizontal divider drags up/down, then releases. */
const DRAGH = (x1, y1, x2, y2, dy, t = HOLD) =>
  A(line(x1, y1, x2, y2), [
    an("y1", [`${y1}`, `${y1}`, `${y1 + dy}`, `${y1}`, `${y1}`], t),
    an("y2", [`${y2}`, `${y2}`, `${y2 + dy}`, `${y2}`, `${y2}`], t),
  ]);
/* a pane swells symmetric about its own center, then relaxes. */
const BREATHE = (x, y, w, h, rx, d = 0.8, t = HOLD) => {
  const q = d / 2;
  return A(rect(x, y, w, h, rx), [
    an("x", [`${x}`, `${x}`, `${f(x - q)}`, `${x}`, `${x}`], t),
    an("y", [`${y}`, `${y}`, `${f(y - q)}`, `${y}`, `${y}`], t),
    an("width", [`${w}`, `${w}`, `${f(w + d)}`, `${w}`, `${w}`], t),
    an("height", [`${h}`, `${h}`, `${f(h + d)}`, `${h}`, `${h}`], t),
  ]);
};

/* Soft keyframe diamond — a rhombus with rounded tips. t pulls each
 * vertex back along its edges; the cubic between them bows toward the
 * tip so points stay perky, not clipped. */
const dia = (cx, cy, rx, ry, t = 0.26) => {
  const V = [
    [cx, cy - ry],
    [cx + rx, cy],
    [cx, cy + ry],
    [cx - rx, cy],
  ];
  let d = "";
  for (let i = 0; i < 4; i++) {
    const p = V[(i + 3) % 4], v = V[i], n = V[(i + 1) % 4];
    const ax = f(v[0] + (p[0] - v[0]) * t), ay = f(v[1] + (p[1] - v[1]) * t);
    const bx = f(v[0] + (n[0] - v[0]) * t), by = f(v[1] + (n[1] - v[1]) * t);
    d += (i === 0 ? "M" : "L") + `${ax} ${ay}`;
    d += `C${f(v[0])} ${f(v[1])} ${f(v[0])} ${f(v[1])} ${bx} ${by}`;
  }
  return d + "Z";
};

/* Half-diamond chevron — an open `>` that bulges out and eases back,
 * like a keyframe sliced down the middle. */
const chev = (x, tx, y0 = 5.2, y1 = 18.8) => {
  const mx = tx - x;
  return `M${x} ${y0}C${f(x + mx * 0.55)} ${f(y0 + 2.4)} ${f(tx - 0.4)} 10.4 ${tx} 12S${f(x + mx * 0.55)} ${f(y1 - 2.4)} ${x} ${y1}`;
};

