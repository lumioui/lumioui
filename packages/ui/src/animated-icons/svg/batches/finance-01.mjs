const path = (d, a = {}) => ({ e: "path", a: { d, ...a } });
const circle = (cx, cy, r, a = {}) => ({ e: "circle", a: { cx, cy, r, ...a } });
const line = (x1, y1, x2, y2, a = {}) => ({ e: "line", a: { x1, y1, x2, y2, ...a } });
const rect = (x, y, w, h, rx, a = {}) => ({ e: "rect", a: { x, y, width: w, height: h, rx, ...a } });
const ellipse = (cx, cy, rx, ry, a = {}) => ({ e: "ellipse", a: { cx, cy, rx, ry, ...a } });
const fill = (color = "currentColor") => ({ fill: color, stroke: "none" });
const A = (part, anims) => ({ ...part, anims });
const G = (id, children, a = {}) => ({ e: "g", g: id, a, children });
const an = (attr, values, times) => ({ kind: "attr", attr, values, times });
const tn = (type, values, times, extra = {}) => ({ kind: "transform", type, values, times, ...extra });

const q = (v) => +v.toFixed(2);

/* Continuous soft rounded-rect silhouette — eased c-curve corners instead of
 * arcs, so the box reads hand-tuned like the canon house/bell. */
const blob = (x, y, w, h, r = 3.6) =>
  path(
    `M${q(x + r)} ${q(y)}h${q(w - 2 * r)}c${q(r * 0.55)} 0 ${q(r)} ${q(r * 0.45)} ${q(r)} ${q(r)}` +
      `v${q(h - 2 * r)}c0 ${q(r * 0.55)} ${q(-r * 0.45)} ${q(r)} ${q(-r)} ${q(r)}` +
      `h${q(-(w - 2 * r))}c${q(-r * 0.55)} 0 ${q(-r)} ${q(-r * 0.45)} ${q(-r)} ${q(-r)}` +
      `v${q(-(h - 2 * r))}c0 ${q(-r * 0.55)} ${q(r * 0.45)} ${q(-r)} ${q(r)} ${q(-r)}z`
  );

/* The bitcoin "B": stem + two lobed bars + tick stubs, four elements.
 * (cx,cy) = glyph center, h = height; width lands ~0.82h. */
const bB = (cx, cy, h) => {
  const top = cy - h / 2;
  const mid = cy;
  const bot = cy + h / 2;
  const sx = cx - 0.34 * h; // bar left edge
  const xr = cx + 0.12 * h; // lobe join
  const st = sx + 0.07 * h; // stem x
  const lobe =
    `c${q(0.26 * h)} ${q(0.01 * h)} ${q(0.34 * h)} ${q(0.1 * h)} ${q(0.34 * h)} ${q(0.24 * h)}` +
    `c0 ${q(0.14 * h)} ${q(-0.08 * h)} ${q(0.26 * h)} ${q(-0.34 * h)} ${q(0.26 * h)}`;
  const t1 = sx + 0.2 * h;
  const t2 = sx + 0.38 * h;
  const tl = 0.14 * h;
  const body = [
    path(`M${q(sx)} ${q(top)}H${q(xr)}${lobe}`),
    path(`M${q(sx)} ${q(mid)}H${q(xr)}${lobe}H${q(sx)}`),
    line(q(st), q(top), q(st), q(bot)),
  ];
  /* Under ~7 units the four tick stubs have no air left and haze the
   * letter into a smudge; a small B keeps a single tick top and bottom
   * on the stem axis so it still reads as the currency mark. */
  if (h < 7) {
    const tx = q(sx + 0.29 * h);
    return [...body, path(`M${tx} ${q(top - 1.1)}V${q(top)}M${tx} ${q(bot)}V${q(bot + 1.1)}`)];
  }
  return [
    ...body,
    path(
      `M${q(t1)} ${q(top - tl)}V${q(top + tl * 0.3)}M${q(t2)} ${q(top - tl)}V${q(top + tl * 0.3)}` +
        `M${q(t1)} ${q(bot - tl * 0.3)}v${q(tl * 1.3)}M${q(t2)} ${q(bot - tl * 0.3)}v${q(tl * 1.3)}`
    ),
  ];
};

