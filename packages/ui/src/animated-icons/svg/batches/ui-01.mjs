/** Soft scalloped seal ring — cosine radius modulation, same trick as the
 *  canon gear's bloom. Badge silhouettes; not machine teeth. */
const sealPath = (cx, cy, lobes = 12, rMid = 8.1, amp = 0.95, steps = 8) => {
  const pts = [];
  for (let i = 0; i < lobes * steps; i++) {
    const t = (i / (lobes * steps)) * Math.PI * 2;
    const r = rMid + amp * Math.cos(lobes * t);
    pts.push(`${(cx + r * Math.cos(t)).toFixed(2)} ${(cy + r * Math.sin(t)).toFixed(2)}`);
  }
  return `M${pts.join("L")}Z`;
};
