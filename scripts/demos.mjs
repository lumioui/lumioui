#!/usr/bin/env node
/**
 * Writes apps/playground/generated/demos.ts from packages/ui/src:
 * - CATALOG groups every component by the `category` in its meta.json;
 * - DEMOS lazily imports each component's demo.tsx (key "<name>") and each
 *   file in variants/ (key "<name>--<slug>").
 *
 * Run it after adding a component, a variant or a demo:
 *   pnpm demos
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "packages/ui/src");
const OUT = path.join(ROOT, "apps/playground/generated/demos.ts");

const ORDER = ["Actions", "Forms & Inputs", "Navigation", "Feedback", "Overlays", "Data Display", "Layout", "Mobile-Native", "Signature"];

/** The first exported component name in a file (export function X / export const X). */
function firstExport(file) {
  const m = fs.readFileSync(file, "utf8").match(/export\s+(?:function|const)\s+([A-Z][A-Za-z0-9]*)/);
  return m?.[1] ?? null;
}

const byCategory = new Map();
const demos = [];
for (const name of fs.readdirSync(SRC).sort()) {
  const dir = path.join(SRC, name);
  const metaFile = path.join(dir, "meta.json");
  if (!fs.statSync(dir).isDirectory() || !fs.existsSync(metaFile)) continue;
  const meta = JSON.parse(fs.readFileSync(metaFile, "utf8"));
  const cat = meta.category ?? "Misc";
  byCategory.set(cat, [...(byCategory.get(cat) ?? []), name]);

  const rel = (f) => `../../../packages/ui/src/${name}/${f}`;
  const demo = path.join(dir, "demo.tsx");
  if (fs.existsSync(demo)) {
    const exp = firstExport(demo) ?? "Demo";
    demos.push(`  ${JSON.stringify(name)}: () => import(${JSON.stringify(rel("demo"))}).then((m) => m.${exp}),`);
  }
  const vDir = path.join(dir, "variants");
  if (fs.existsSync(vDir)) {
    for (const f of fs.readdirSync(vDir).sort()) {
      if (!f.endsWith(".tsx")) continue;
      const exp = firstExport(path.join(vDir, f));
      if (!exp) continue;
      const slug = f.replace(/\.tsx$/, "");
      demos.push(`  ${JSON.stringify(`${name}--${slug}`)}: () => import(${JSON.stringify(rel(`variants/${slug}`))}).then((m) => m.${exp}),`);
    }
  }
}

const rank = (c) => (ORDER.indexOf(c) === -1 ? 99 : ORDER.indexOf(c));
const catalog = [...byCategory.keys()]
  .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))
  .map((category) => ({ category, names: byCategory.get(category) }));

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  `// Generated by scripts/demos.mjs. Run \`pnpm demos\` after adding a component, variant or demo.
import type * as React from "react";

export const CATALOG: { category: string; names: string[] }[] = ${JSON.stringify(catalog, null, 2)};

export const DEMOS: Record<string, () => Promise<React.ComponentType>> = {
${demos.join("\n")}
};
`,
);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${catalog.reduce((n, g) => n + g.names.length, 0)} components, ${demos.length} demos`);
